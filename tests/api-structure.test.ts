// The structure of /api/v1 is locked: the API has exactly the recorded structure, and the record only grows from 1.0.0.
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { isDeepStrictEqual } from "node:util";
import { describe, expect, it } from "vitest";
import { apiStructure, breaksMessage, readRecord, structureBreaks, type Structure } from "../scripts/lib/api-structure.ts";
import { ENDPOINTS, openapi } from "../src/core/openapi.ts";
import { ROOT } from "./helpers.ts";

const RECORD = join(ROOT, "structure", "api-v1.json");
const BASELINE = join(ROOT, "structure", "api-v1-1.0.0.json");
/** The baseline is never edited. A change to it fails here, whatever else is changed with it. */
const BASELINE_SHA256 = "abed0774ad6dae9db91a50f373174ec2df2adb7bea40438da454b127f05e9f74";

const record = (): Structure => readRecord(readFileSync(RECORD, "utf8"));
const baseline = (): Structure => readRecord(readFileSync(BASELINE, "utf8"));

/** Where two structures differ, as dotted keys, for a failure message. */
function differences(a: unknown, b: unknown, where = "", out: string[] = []): string[] {
  if (isDeepStrictEqual(a, b)) return out;
  const isObject = (value: unknown): value is Record<string, unknown> => value !== null && typeof value === "object" && !Array.isArray(value);
  if (isObject(a) && isObject(b)) {
    for (const key of new Set([...Object.keys(a), ...Object.keys(b)])) {
      if (!(key in a)) out.push(`${where}${key}: new`);
      else if (!(key in b)) out.push(`${where}${key}: gone`);
      else differences(a[key], b[key], `${where}${key}.`, out);
    }
  } else out.push(`${where.replace(/\.$/, "")}: ${JSON.stringify(a)} in the record, ${JSON.stringify(b)} in the code`);
  return out;
}

describe("the structure of /api/v1", () => {
  it("is exactly the record in structure/api-v1.json", () => {
    const now = apiStructure(openapi());
    const found = differences(record(), now);
    expect(
      found,
      [
        "The structure of the API generated by the code is not the one recorded in structure/api-v1.json:",
        ...found.slice(0, 30).map((item) => `  - ${item}`),
        "If the change is meant, run `npm run structure:update` and commit the record with it. The record may only grow from 1.0.0, and a release that adds something takes a minor version step.",
      ].join("\n"),
    ).toEqual([]);
  });

  it("only grows from 1.0.0: the record takes nothing away from structure/api-v1-1.0.0.json", () => {
    const breaks = structureBreaks(baseline(), record());
    expect(breaks, breaksMessage(breaks)).toEqual([]);
  });

  it("keeps the baseline of 1.0.0 as it was written", () => {
    const sha = createHash("sha256").update(readFileSync(BASELINE)).digest("hex");
    expect(sha, "structure/api-v1-1.0.0.json is the structure of 1.0.0 and is never edited. A change that needs it edited belongs in /api/v2.").toBe(BASELINE_SHA256);
  });

  it("has a version above 1.0.0 once the record has grown beyond the baseline", () => {
    const version = (openapi() as { info: { version: string } }).info.version;
    const [major, minor] = version.split(".").map(Number);
    expect(version).toMatch(/^\d+\.\d+\.\d+$/);
    expect(major, "/api/v1 is version 1.x.y. A version 2 would be /api/v2.").toBe(1);
    // Grown: different from the baseline and taking nothing from it (a record that takes something away fails above).
    if (!isDeepStrictEqual(record(), baseline()) && structureBreaks(baseline(), record()).length === 0) {
      expect(minor, `The structure has grown beyond 1.0.0 and the version is still ${version}. A release that adds something takes a minor step: 1.1.0, then 1.2.0, in src/core/openapi.ts.`).toBeGreaterThanOrEqual(1);
    }
  });
});

describe("the promise in words", () => {
  it("is a guide section Stability of the OpenAPI document, after Requests and pagination", () => {
    const guide = (openapi() as { "x-guide": { id: string; title: string; paragraphs: string[] }[] })["x-guide"];
    const ids = guide.map((section) => section.id);
    expect(ids.indexOf("stability")).toBe(ids.indexOf("usage") + 1);
    const section = guide.find((item) => item.id === "stability")!;
    expect(section.title).toBe("Stability");
    const text = section.paragraphs.join(" ");
    for (const words of [
      "/api/v1 only grows.", "Nothing in it is removed, renamed or retyped", "must ignore keys it does not know", "must tolerate a value of an enumerated field that it does not know",
      "would be /api/v2, published beside /api/v1, which is kept", "info.version", "started at 1.0.0 with the first public release", "takes a minor step", "X-Dataset-Version", "They are not this version.",
    ]) expect(text, words).toContain(words);
  });

  it("is in the README, under One contract, with the command that updates the record, and in AGENTS.md, under Rules", () => {
    const readme = readFileSync(join(ROOT, "README.md"), "utf8").replace(/\s+/g, " ");
    const contract = readme.slice(readme.indexOf("### One contract"), readme.indexOf("## Deploying"));
    for (const words of ["`npm run structure:update`", "structure/api-v1.json", "structure/api-v1-1.0.0.json", "/api/v2", "1.0.0"]) expect(contract, words).toContain(words);
    const agents = readFileSync(join(ROOT, "AGENTS.md"), "utf8").replace(/\s+/g, " ");
    const rules = agents.slice(agents.indexOf("## Rules"), agents.indexOf("## Commands"));
    for (const words of ["only grows", "structure/api-v1-1.0.0.json", "never edited", "`npm run structure:update`", "same commit", "minor"]) expect(rules, words).toContain(words);
  });
});

describe("what counts as growth and what as a break", () => {
  type Doc = Record<string, unknown> & {
    info: { description: string };
    "x-guide": { paragraphs: string[] }[];
    paths: Record<string, { get: { summary: string; parameters: Record<string, unknown>[]; responses: Record<string, unknown> } }>;
    components: { schemas: Record<string, { [key: string]: unknown; description?: string; properties: Record<string, Record<string, unknown>>; required: string[] }> };
  };
  const fresh = (): Doc => structuredClone(openapi()) as Doc;
  const base = apiStructure(openapi());
  const breaksAfter = (change: (doc: Doc) => void, endpoints = ENDPOINTS): string[] => {
    const doc = fresh();
    change(doc);
    return structureBreaks(base, apiStructure(doc, endpoints));
  };
  const schemas = (doc: Doc) => doc.components.schemas;
  const parameters = (doc: Doc, path: string) => doc.paths[path]!.get.parameters;

  it("reads no prose: descriptions, summaries, examples and the guide can change", () => {
    const doc = fresh();
    doc.info.description = "Another description.";
    doc["x-guide"][0]!.paragraphs = ["Another guide."];
    doc.paths["/api/v1/entries"]!.get.summary = "Another summary.";
    schemas(doc).InputWindow!.description = "Another description.";
    schemas(doc).InputWindow!.properties.tokens!.description = "Another description.";
    parameters(doc, "/api/v1/entries")[0]!.description = "Another description.";
    delete (schemas(doc).Pricing as Record<string, unknown>).examples;
    expect(apiStructure(doc)).toEqual(base);
  });

  it.each<[string, (doc: Doc) => void]>([
    ["a new path", (doc) => void (doc.paths["/api/v1/new"] = { get: { summary: "New", parameters: [], responses: { 200: { description: "ok", content: { "application/json": { schema: { type: "object" } } } } } } })],
    ["a new optional parameter", (doc) => void parameters(doc, "/api/v1/entries").push({ name: "new_filter", in: "query", required: false, schema: { type: "string" } })],
    ["a new allowed value of a parameter", (doc) => void ((parameters(doc, "/api/v1/entries").find((param) => param.name === "sort")!.schema as { enum: string[] }).enum.push("new_sort"))],
    ["a new property in a response schema", (doc) => void (schemas(doc).InputWindow!.properties.new_key = { type: ["integer", "null"] })],
    ["a new required property in a response schema", (doc) => void ((schemas(doc).InputWindow!.properties.new_key = { type: "integer" }), schemas(doc).InputWindow!.required.push("new_key"))],
    ["a new component", (doc) => void (schemas(doc).NewThing = { type: "object", properties: { id: { type: "string" } }, required: ["id"] })],
    ["a new enum value in a response", (doc) => void (schemas(doc).InputWindow!.properties.basis!.enum as string[]).push("estimated")],
    ["a nullable property that can no longer be null", (doc) => void (schemas(doc).InputWindow!.properties.date = { type: "string", pattern: "^\\d{4}-\\d{2}-\\d{2}$" })],
    ["a new header", (doc) => void ((doc.paths["/api/v1/meta"]!.get.responses[200] as { headers: Record<string, unknown> }).headers["X-New"] = { schema: { type: "string" } })],
  ])("allows %s", (_name, change) => {
    const breaks = breaksAfter(change);
    expect(breaks, breaksMessage(breaks)).toEqual([]);
  });

  it("allows a new allowed value of a list parameter, and refuses one taken away", () => {
    const endpoints = (values: string[]) => ENDPOINTS.map((endpoint) => (endpoint.path === "/api/v1/entries" ? { ...endpoint, params: endpoint.params.map((param) => (param.name === "access" ? { ...param, values } : param)) } : endpoint));
    expect(breaksAfter(() => undefined, endpoints(["api", "subscription", "unknown", "free"]))).toEqual([]);
    expect(breaksAfter(() => undefined, endpoints(["api", "subscription"]))).toEqual(['GET /api/v1/entries, query parameter access: the allowed value "unknown" is gone']);
  });

  it.each<[string, (doc: Doc) => void, string]>([
    ["a removed path", (doc) => void delete doc.paths["/api/v1/facets"], "/api/v1/facets: the path is gone (removed or renamed)"],
    ["a renamed path", (doc) => void ((doc.paths["/api/v1/evaluations/limit"] = doc.paths["/api/v1/evaluations/limits"]!), delete doc.paths["/api/v1/evaluations/limits"]), "/api/v1/evaluations/limits: the path is gone (removed or renamed)"],
    ["a removed parameter", (doc) => void doc.paths["/api/v1/entries"]!.get.parameters.splice(parameters(doc, "/api/v1/entries").findIndex((param) => param.name === "min_context"), 1), "GET /api/v1/entries, query parameter min_context: the parameter is gone (removed or renamed)"],
    ["a renamed parameter", (doc) => void (parameters(doc, "/api/v1/entries").find((param) => param.name === "min_output")!.name = "min_max_output"), "GET /api/v1/entries, query parameter min_output: the parameter is gone (removed or renamed)"],
    ["a removed property", (doc) => void delete schemas(doc).InputWindow!.properties.scope, "InputWindow: the property scope is gone (removed or renamed)"],
    ["a renamed property", (doc) => void ((schemas(doc).SafeLifetime!.properties.safe_seconds = schemas(doc).SafeLifetime!.properties.safe_s!), delete schemas(doc).SafeLifetime!.properties.safe_s), "SafeLifetime: the property safe_s is gone (removed or renamed)"],
    ["a removed component", (doc) => void delete schemas(doc).Facets, "Facets: the component is gone (removed or renamed)"],
    ["a changed type", (doc) => void (schemas(doc).InputWindow!.properties.tokens = { type: ["string", "null"] }), "InputWindow.tokens: was integer and is now string, a changed type"],
    ["a property always present that may now be absent", (doc) => void (schemas(doc).InputWindow!.required = schemas(doc).InputWindow!.required.filter((key) => key !== "bound")), "InputWindow.bound: was always present and now may be absent"],
    ["a property that could not be null becoming nullable", (doc) => void (schemas(doc).InputWindow!.properties.clients = { type: ["integer", "null"], minimum: 0 }), "InputWindow.clients: could not be null in 1.0.0 and now can be null"],
    ["a new required parameter", (doc) => void parameters(doc, "/api/v1/entries").push({ name: "key", in: "query", required: true, schema: { type: "string" } }), "GET /api/v1/entries, query parameter key: a new parameter that is required (a new parameter must be optional)"],
    ["an optional parameter becoming required", (doc) => void (parameters(doc, "/api/v1/entries").find((param) => param.name === "q")!.required = true), "GET /api/v1/entries, query parameter q: was optional and is now required"],
    ["a removed allowed value of a parameter", (doc) => void ((parameters(doc, "/api/v1/entries").find((param) => param.name === "order")!.schema as { enum: string[] }).enum = ["asc"]), 'GET /api/v1/entries, query parameter order: the allowed value "desc" is gone'],
    ["a removed enum value in a response", (doc) => void (schemas(doc).InputWindow!.properties.bound!.anyOf = [{ type: "string", enum: ["limit"] }, { type: "null" }]), 'InputWindow.bound: the value "at_least" is gone'],
    ["a narrower parameter range", (doc) => void ((parameters(doc, "/api/v1/entries").find((param) => param.name === "limit")!.schema as { maximum: number }).maximum = 100), "GET /api/v1/entries, query parameter limit: the highest value allowed was 200 and is now 100"],
    ["a removed response", (doc) => void delete doc.paths["/api/v1/meta"]!.get.responses[304], "GET /api/v1/meta, response 304: the response is gone"],
    ["a removed header", (doc) => void delete (doc.paths["/api/v1/meta"]!.get.responses[200] as { headers: Record<string, unknown> }).headers["X-Dataset-Version"], "GET /api/v1/meta, response 200, header X-Dataset-Version: the header is gone"],
  ])("refuses %s, saying what broke", (_name, change, words) => {
    const breaks = breaksAfter(change);
    expect(breaks).toContain(words);
    expect(breaksMessage(breaks)).toMatch(/belongs in \/api\/v2, with \/api\/v1 kept as it is/);
  });

  it("follows a property into every schema that uses it: a property removed from a component breaks each answer and component that carries it", () => {
    const breaks = breaksAfter((doc) => void delete schemas(doc).InputWindowMeasurement!.properties.read);
    expect(breaks).toContain("InputWindowMeasurement: the property read is gone (removed or renamed)");
  });
});
